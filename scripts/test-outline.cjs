const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const { marked } = require('marked');
const { sections } = require('../outline-model');
const root = path.resolve(__dirname, '..');
const source = '# Book\nIntro\n\n## A\nAlpha\n\n### Child\n```js\n# not heading\n```\n\n## B\nBeta\n\nDeep\n----\nFive\n\n###### Last\nSix\n';
const ranges = sections(source, s => marked.lexer(s));
assert.deepEqual(ranges.map(s=>s.level),[1,2,3,2,2,6]);
assert.equal(ranges[1].end,10);
assert.equal(ranges[4].headerEnd,15);
assert.equal(ranges.length,6);
assert.notEqual(sections('## Same\na\n## Same\nb', s => marked.lexer(s))[0].key,sections('## Same\na\n## Same\nb', s => marked.lexer(s))[1].key);
console.log('PASS: source mapping (fences, hierarchy, setext, duplicate headings)');
if (!process.env.OUTLINE_TEST_JSDOM) {
  console.log('DOM checks skipped: set OUTLINE_TEST_JSDOM to an installed jsdom package path.');
  process.exit(0);
}
const { JSDOM } = require(process.env.OUTLINE_TEST_JSDOM);
const dom = new JSDOM('<html><body><button id="outline-collapse-all"></button><button id="outline-expand-all"></button><div><div class="editor-gutter"></div><textarea></textarea></div><div id="preview"></div><div id="tree"></div></body></html>',{runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;
w.focus=()=>{};
w.Range.prototype.getBoundingClientRect=()=>({left:0,right:100,top:0,bottom:20,width:100,height:20});
w.Range.prototype.getClientRects=()=>[];
for(const file of ['assets/codemirror/codemirror.js','source-editor.js','article-outline.js']) w.eval(fs.readFileSync(path.join(root,file),'utf8'));
const editor=w.createSourceEditor(w.document.querySelector('textarea'));
const preview=w.document.getElementById('preview'),tree=w.document.getElementById('tree');
const renderer=new marked.Renderer();
renderer.heading=(text,level)=>`<h${level} data-outline-heading="true">${text}</h${level}>`;
let tab={content:source,outlineState:new Set()};
editor.loadTab(tab);
const outline=new w.ArticleOutline(editor,preview,tree,()=>{});
const rebuild=()=>{
  preview.innerHTML=marked.parse(editor.value,{renderer});
  outline.rebuild(sections(editor.value,s=>marked.lexer(s)),tab.outlineState);
};
rebuild();
assert.equal(tree.querySelectorAll('button').length,6);
outline.toggle(outline.sections[1]);
assert.equal(editor.value,source);
assert.equal(outline.marks.length,1);
assert.ok(preview.querySelector('p.outline-content-hidden'));
assert.equal(outline.sections[1].button.getAttribute('aria-expanded'),'false');
outline.toggle(outline.sections[2]);
assert.ok(!tab.outlineState.has(outline.sections[1].key),'click child reveals parent');
assert.ok(tab.outlineState.has(outline.sections[2].key));
outline.toggle(outline.sections[1]);
assert.equal(outline.marks.length,1,'outer fold replaces overlapping child mark');
outline.toggle(outline.sections[1]);
assert.ok(tab.outlineState.has(outline.sections[2].key),'child state restored');
outline.setAll(true);
assert.equal(outline.marks.length,1);
assert.equal(editor.value,source,'collapse all preserves source');
const exported=w.ArticleOutline.exportHtml(preview);
assert.ok(!exported.includes('outline-content-hidden'));
assert.ok(exported.includes('Alpha') && exported.includes('Six'));
assert.ok(preview.querySelector('.outline-content-hidden'),'export preserves reading state');
editor.setSelectionRange(source.indexOf('Alpha'),source.indexOf('Alpha')+5);
assert.equal(editor.cm.getSelection(),'Alpha','search can select hidden text');
assert.ok(!tab.outlineState.has(outline.sections[1].key));
editor.replaceSelection('Revised');
rebuild();
assert.ok(editor.value.includes('Revised'));
assert.ok(editor.value.includes('# not heading'),'editing preserves other hidden text');
editor.cm.undo(); rebuild();
assert.equal(editor.value,source,'undo includes complete source');
editor.cm.redo(); rebuild();
assert.ok(editor.value.includes('Revised'));
outline.setAll(false);
assert.equal(outline.marks.length,0);
assert.ok(!preview.querySelector('.outline-content-hidden'));
const firstTab=tab;
firstTab.content=editor.value;
outline.setAll(true);
outline.clearMarks();
tab={content:'# Other\nAnother body',outlineState:new Set()};
editor.loadTab(tab);rebuild();
assert.equal(outline.marks.length,0);
editor.cm.undo();
assert.equal(editor.value,tab.content,'undo history isolated per tab');
outline.clearMarks();tab=firstTab;editor.loadTab(tab);rebuild();
assert.equal(outline.marks.length,1);
assert.equal(editor.value,firstTab.content);
outline.setAll(false);
// Replacing full-source values (formatting/save-as paths) must retain hidden content.
outline.toggle(outline.sections[1]);
editor.value=editor.value.replace('Revised','Edited');rebuild();
assert.ok(editor.value.includes('Edited'));
assert.ok(editor.value.includes('Six'));
outline.setAll(true);
const beforeDelete=editor.value;
editor.cm.replaceRange('',{line:0,ch:0},editor.cm.posFromIndex(editor.value.length),'+delete');
assert.equal(editor.value,beforeDelete,'deleting across a hidden range first reveals it without data loss');
console.log('PASS: DOM/editor integration (outline toggles, nested folds, clean exports, search, editing, undo/redo, tab isolation)');
w.close();
