const fs=require('fs'),assert=require('node:assert/strict');
const {JSDOM}=require(process.env.OUTLINE_TEST_JSDOM || 'jsdom');
const dom=new JSDOM('<div><textarea></textarea></div>',{runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;
w.Range.prototype.getBoundingClientRect=()=>({left:0,right:100,top:0,bottom:20,width:100,height:20});
w.Range.prototype.getClientRects=()=>[];
for(const file of ['assets/codemirror/codemirror.js','source-editor.js']) w.eval(fs.readFileSync(file,'utf8'));
const editor=w.createSourceEditor(w.document.querySelector('textarea'));
const calls=[];
editor.cm.scrollTo=(...args)=>calls.push(args);
w.CodeMirror.signal(editor.cm,'scroll',editor.cm);
assert.equal(calls.length,0,'a source scroll notification must not call scrollTo and reset the source position');
assert.equal(Object.hasOwn(editor,'scrollTop'),false,'leave CodeMirror wrapper geometry native');
let notifications=0;
editor.addEventListener('source-scroll',()=>notifications++);
w.CodeMirror.signal(editor.cm,'scroll',editor.cm);
assert.equal(notifications,1);
editor.cm.getScrollInfo=()=>({top:180,height:1500,clientHeight:400});
assert.equal(editor.sourceScrollTop,180);
assert.equal(editor.sourceScrollHeight,1500);
assert.equal(editor.sourceClientHeight,400);
editor.sourceScrollTop=220;
assert.deepEqual(calls,[[null,220]]);
console.log('PASS: scroll notifications do not reset position; source metrics remain separate from wrapper geometry');
w.close();
